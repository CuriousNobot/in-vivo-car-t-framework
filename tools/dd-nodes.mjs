function sec(key, zh, en, html) {
  return { key, title: zh, title_en: en, html };
}

export function buildNodes(route) {
  const L = route === "LNP";
  const K = refFor(route);
  const S = (...keys) => keys.map(K);
  const c = (...keys) => cite(S(...keys));
  const ctx = { L, K, S, c };
  const nodes = [
    ...summaryNodes(ctx),
    ...positionNodes(ctx),
    ...(L ? lnpMechanism(ctx) : lvMechanism(ctx)),
    ...devNodes(ctx),
    ...assuranceNodes(ctx),
    ...landscapeNodes(ctx, route),
    ...commercialNodes(ctx),
    ...decisionNodes(ctx, route),
  ];
  return nodes.map((n) => ({ ...n, sources: [...new Set((n.sources || []).map(K))] }));
}

